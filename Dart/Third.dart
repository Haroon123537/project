//Looking at more advanced variable datatypes that are var, dynamic, final, const
main(){
  //var datatype
  var name= "Haroon Rafi";
  print(name);
  name="Saqlain Mushtaq";
  print(name);

  //dynamic datatype
  dynamic age=24;
  print(age);
  age="Abbas Afridi";
  print(age);

  //Final datatype
  final hobby='Cricket';
  print(hobby);
  print(hobby);

  //Const datatype
  const futureaim='App development';
  print(futureaim);  
}
